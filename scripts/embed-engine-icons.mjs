// 将 assets/icons/ 下的引擎图标内联为 base64 data URL 模块。
//
// 背景：Plasmo 0.90 不支持 static_assets，运行时拼接的
// chrome.runtime.getURL("icons/x.ico") 在正式包里 404（内容脚本还额外受
// web_accessible_resources 限制）。构建期把图标编成 data URL 直接从 JS 里取，
// 零网络、零 WAR、离线可用。
//
// 用法：node scripts/embed-engine-icons.mjs（已挂到 prebuild/prepackage）
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ICONS_DIR = resolve(__dirname, "../assets/icons")
const OUT_FILE = resolve(__dirname, "../src/services/engineIcons.generated.ts")

const MIME_BY_EXT = {
  ".ico": "image/x-icon",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".svg": "image/svg+xml",
  ".gif": "image/gif",
  ".webp": "image/webp"
}

function build() {
  if (!existsSync(ICONS_DIR)) {
    console.warn(`[embed-engine-icons] 图标目录不存在: ${ICONS_DIR}，生成空映射`)
    writeFileSync(OUT_FILE, generateModule({}))
    return
  }

  const entries = {}
  for (const file of readdirSync(ICONS_DIR).sort()) {
    const ext = file.slice(file.lastIndexOf(".")).toLowerCase()
    const base = file.slice(0, file.lastIndexOf("."))
    const mime = MIME_BY_EXT[ext]
    if (!mime) continue
    const buffer = readFileSync(join(ICONS_DIR, file))
    entries[base] = `data:${mime};base64,${buffer.toString("base64")}`
  }

  writeFileSync(OUT_FILE, generateModule(entries))
  console.log(`[embed-engine-icons] 已内联 ${Object.keys(entries).length} 个图标 -> src/services/engineIcons.generated.ts`)
}

function generateModule(entries) {
  const body = Object.entries(entries)
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
    .join(",\n")
  return `// AUTO-GENERATED by scripts/embed-engine-icons.mjs — 请勿手动编辑。\nexport const EMBEDDED_ENGINE_ICONS: Record<string, string> = {\n${body ? body + ",\n" : ""}}\n`
}

build()
